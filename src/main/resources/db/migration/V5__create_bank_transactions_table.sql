CREATE TABLE bank_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reference_id VARCHAR(36) NOT NULL,

    bank_account_id BIGINT NOT NULL,

    transaction_type VARCHAR(20) NOT NULL,

    amount NUMERIC(19, 2) NOT NULL,

    balance_after NUMERIC(19, 2) NOT NULL,

    description VARCHAR(255),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_bank_transactions_reference
        UNIQUE (reference_id),

    CONSTRAINT fk_bank_transactions_account
        FOREIGN KEY (bank_account_id)
        REFERENCES bank_accounts(id),

    CONSTRAINT chk_bank_transactions_type
        CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL')),

    CONSTRAINT chk_bank_transactions_amount
        CHECK (amount > 0),

    CONSTRAINT chk_bank_transactions_balance
        CHECK (balance_after >= 0)
);

CREATE INDEX idx_bank_transactions_account_created_at
    ON bank_transactions (bank_account_id, created_at DESC);