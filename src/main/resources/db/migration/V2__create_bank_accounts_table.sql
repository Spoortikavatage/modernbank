
CREATE TABLE bank_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(12) NOT NULL,
    user_id BIGINT NOT NULL,
    account_type VARCHAR(20) NOT NULL DEFAULT 'SAVINGS',
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    balance NUMERIC(19, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_bank_accounts_account_number
        UNIQUE (account_number),

    CONSTRAINT fk_bank_accounts_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT chk_bank_accounts_type
        CHECK (account_type IN ('SAVINGS', 'CURRENT')),

    CONSTRAINT chk_bank_accounts_balance
        CHECK (balance >= 0),

    CONSTRAINT chk_bank_accounts_status
        CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED'))
);

CREATE INDEX idx_bank_accounts_user_id
    ON bank_accounts(user_id);
